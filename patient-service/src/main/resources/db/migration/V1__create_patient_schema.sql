-- Patient schema, third normal form.
--
-- Functional dependencies and the 1NF -> 2NF -> 3NF derivation are written up in
-- docs/normalisation-3nf.md. The property that carries the constraint here is the
-- address split: a separate table with a UNIQUE foreign key gives a 1:0..1
-- relation, so a missing address is a missing row rather than a NULL that could
-- mean "not captured yet", "the patient declined" or "lost on import".
--
-- gender stays a column on patient. It holds the code alone, with no label
-- beside it, so nothing depends on it transitively and the table is already in
-- 3NF. A reference table would add a join without changing the normal form.

CREATE TABLE patient (
    id           BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name   VARCHAR(60) NOT NULL,
    last_name    VARCHAR(60) NOT NULL,
    birth_date   DATE        NOT NULL,
    gender       CHAR(1)     NOT NULL CHECK (gender IN ('F', 'M')),
    -- Optional for a valid record, per the sprint 1 user story.
    phone_number VARCHAR(20)
);

CREATE TABLE address (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- UNIQUE NOT NULL is what makes the relation 1:0..1 rather than 1:N.
    patient_id BIGINT       NOT NULL UNIQUE REFERENCES patient (id) ON DELETE CASCADE,
    street     VARCHAR(120) NOT NULL
);
